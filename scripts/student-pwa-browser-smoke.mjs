async function checkAccessibility(page, label) {
  if (!await page.evaluate(() => Boolean(window.axe))) await page.addScriptTag({ url: base + '/__test-tools/axe.min.js' });
  const results = await page.evaluate(async () => {
    const result = await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa', 'best-practice'] } });
    return { violations: result.violations.map(item => ({ id: item.id, impact: item.impact, targets: item.nodes.map(node => node.target) })), incomplete: result.incomplete.map(item => item.id) };
  });
  accessibility.push({ label, ...results });
  assert.deepEqual(results.violations, [], `Accessibility violations in ${label}`);
}
