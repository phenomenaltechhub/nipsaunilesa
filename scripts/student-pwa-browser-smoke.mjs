import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createRequire } from 'node:module';
import { startStaticServer } from './lib/static-server.mjs';
import { cacheName, publicAssets } from '../student-pwa/src/pwa/cache-policy.js';
const { chromium } = createRequire(import.meta.url)('playwright');
const directory = process.env.PHARMAIDEIA_REVIEW_DIR || '/workspace/artifacts/pharmaideia-m1';
await fs.mkdir(directory, { recursive: true });
// Test an exact isolated copy; the update check changes only its public shell
// version. No production source or private fixtures are modified by this suite.
const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'pharmaideia-browser-'));
const appRoot = path.join(temporary, 'student-pwa');
await fs.cp(path.resolve('student-pwa'), appRoot, { recursive: true });
const { server, base } = await startStaticServer(appRoot);
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const captures = [];
async function capture(page, name) {
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: path.join(directory, name), fullPage: true, animations: 'disabled' });
  captures.push(name);
}
try {
  for (const viewport of [{ width: 1440, height: 1050 }, { width: 390, height: 844 }, { width: 320, height: 900 }, { width: 768, height: 1024 }]) {
    const context = await browser.newContext({ viewport, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = []; const thirdParty = []; const policyErrors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (!request.url().startsWith(base)) thirdParty.push(request.url()); });
    await page.addInitScript(() => {
      for (const storage of ['localStorage', 'sessionStorage']) Object.defineProperty(window, storage, { get() { throw new DOMException('Storage denied', 'SecurityError'); } });
      document.addEventListener('securitypolicyviolation', event => console.error('POLICY_VIOLATION:' + event.violatedDirective));
    });
    page.on('console', message => { if (message.text().startsWith('POLICY_VIOLATION:')) policyErrors.push(message.text()); });
    assert.equal((await page.goto(base, { waitUntil: 'networkidle' })).status(), 200);
    await page.getByRole('heading', { name: 'Your academic companion', exact: true }).waitFor();
    assert.equal(await page.locator('main').count(), 1);
    await page.keyboard.press('Tab');
    assert.equal(await page.locator('.skip-link').evaluate(node => document.activeElement === node), true);
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('main').evaluate(node => document.activeElement === node), true);
    if (viewport.width === 1440 || viewport.width === 390) await capture(page, `${viewport.width}-overview.png`);
    await page.evaluate(() => { location.hash = '/courses'; });
    const search = page.getByLabel('Search courses'); await search.waitFor();
    await search.fill('<img src=x onerror=alert(1)>');
    await page.getByRole('status').filter({ hasText: '<img src=x onerror=alert(1)>' }).waitFor();
    assert.equal(await page.locator('main img').count(), 0, 'Search text is escaped, not parsed as HTML');
    assert.equal(await page.locator('input[type=password], input[type=email], input[type=file]').count(), 0);
    await search.fill('x'.repeat(120));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Long search text cannot break mobile layout');
    await search.fill('');
    if (viewport.width === 1440 || viewport.width === 390) await capture(page, `${viewport.width}-courses.png`);
    await page.evaluate(() => { location.hash = '/planner'; });
    await page.getByLabel('Session length').selectOption('15');
    await page.getByRole('button', { name: 'Start session', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Focus session in progress.' }).waitFor();
    await page.getByRole('button', { name: 'Pause session', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Session paused.' }).waitFor();
    await page.getByRole('button', { name: 'Resume session', exact: true }).click();
    await page.getByRole('button', { name: 'Reset timer', exact: true }).click();
    assert.equal(await page.getByRole('timer').textContent(), '15:00');
    await page.locator('.skip-link').focus();
    await page.keyboard.press('Enter');
    assert.equal(new URL(page.url()).hash, '#/planner', 'Skip link preserves the current application view');
    if (viewport.width === 1440 || viewport.width === 390) await capture(page, `${viewport.width}-planner.png`);
    if (viewport.width < 760) {
      await page.getByRole('button', { name: 'More', exact: true }).click();
      await page.getByRole('dialog').waitFor();
      await page.getByRole('dialog').getByRole('link', { name: 'Community', exact: true }).click();
      assert.equal(await page.getByRole('dialog').isVisible(), false);
    } else await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('link', { name: 'Community', exact: true }).click();
    await page.getByRole('heading', { name: 'The community is not open', exact: true }).waitFor();
    assert.equal(await page.locator('textarea,[contenteditable=true]').count(), 0);
    if (viewport.width === 1440 || viewport.width === 390) await capture(page, `${viewport.width}-community.png`);
    await page.evaluate(() => { location.hash = '/profile'; });
    await page.getByRole('button', { name: 'Check service availability' }).click();
    await page.getByRole('status').filter({ hasText: 'No request was sent and no account was created.' }).waitFor();
    await page.evaluate(() => { location.hash = '/admin'; });
    await page.getByRole('heading', { name: 'Find your next step' }).waitFor();
    await page.getByRole('link', { name: 'Return to overview' }).click();
    await page.evaluate(() => navigator.serviceWorker.ready);
    await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
    const cached = await page.evaluate(async name => (await (await caches.open(name)).keys()).map(request => request.url), cacheName);
    assert.deepEqual(cached.sort(), publicAssets.map(asset => new URL(asset, base + '/').href).sort());
    await page.evaluate(async () => { await fetch('/api/private-records').catch(() => {}); });
    const after = await page.evaluate(async name => (await (await caches.open(name)).keys()).length, cacheName);
    assert.equal(after, publicAssets.length, 'Unlisted responses never enter the shell cache');
    await context.setOffline(true);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.getByRole('heading', { name: 'Your academic companion', exact: true }).waitFor();
    await page.getByRole('status').filter({ hasText: 'Offline · local tools' }).waitFor();
    await page.evaluate(() => { location.hash = '/planner'; });
    await page.getByRole('button', { name: 'Start session', exact: true }).click();
    await page.getByRole('button', { name: 'Pause session', exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'No horizontal overflow');
    assert.deepEqual(errors, []); assert.deepEqual(thirdParty, []); assert.deepEqual(policyErrors, []);
    console.log(`PASS PWA ${viewport.width}x${viewport.height}: keyboard navigation, safe search, focus controls, closed community, fail-closed account boundary, 25 public-only cached assets, offline reload/local use, denied storage, zero third-party requests/runtime or CSP errors.`);
    await context.close();
  }
  const updateContext = await browser.newContext();
  const updatePage = await updateContext.newPage();
  await updatePage.goto(base);
  await updatePage.evaluate(() => navigator.serviceWorker.ready);
  await updatePage.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await updatePage.evaluate(() => { location.hash = '/planner'; });
  await updatePage.getByRole('button', { name: 'Start session', exact: true }).waitFor();
  const policy = path.join(appRoot, 'src/pwa/cache-policy.js');
  const versioned = (await fs.readFile(policy, 'utf8')).replace('${cachePrefix}v1', '${cachePrefix}v2');
  await fs.writeFile(policy, versioned);
  await fs.appendFile(path.join(appRoot, 'sw.js'), '\n// Isolated browser test: public shell version two.\n');
  await updatePage.evaluate(async () => { await (await navigator.serviceWorker.getRegistration()).update(); });
  await updatePage.getByRole('button', { name: 'Reload app', exact: true }).waitFor();
  assert.equal(await updatePage.getByRole('heading', { name: 'Make time for learning', exact: true }).count(), 1, 'Update waits for user choice');
  await Promise.all([updatePage.waitForNavigation({ waitUntil: 'domcontentloaded' }), updatePage.getByRole('button', { name: 'Reload app', exact: true }).click()]);
  await updatePage.getByRole('heading', { name: 'Make time for learning', exact: true }).waitFor();
  const activeCaches = await updatePage.evaluate(() => caches.keys());
  assert.ok(activeCaches.includes('pharmaideia-public-shell-v2'));
  assert.ok(!activeCaches.includes(cacheName), 'Activation removes only obsolete app shell cache');
  console.log('PASS PWA update: changed worker installs, waits without reloading, explicit reload applies version two and removes obsolete shell cache.');
  await updateContext.close();
  await fs.writeFile(path.join(directory, 'REVIEW.md'), '# PHARMAIDEIA M1 component review\n\nActual standalone PWA screenshots. No student identities, courses, messages or payment records are fabricated. Accounts, payments, permissions and real-time community remain unavailable. Local focus controls, offline shell and explicit update application are implemented and browser-tested.\n\n' + captures.map(name => `- [${name}](${path.join(directory, name)})`).join('\n') + '\n');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); await fs.rm(temporary, { recursive: true, force: true }); }
